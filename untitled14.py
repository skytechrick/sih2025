def get_agri_insights(row):
    temp = row["temperature_2m"]
    humidity = row["relative_humidity_2m"]
    precip = row["precipitation"]
    wind_speed = row["wind_speed_10m"]
    soil_temp = row["soil_temperature_0cm"]
    soil_moisture = row["soil_moisture_0_1cm"]
    wsi = row["water_stress_index"]
    gdd = row["growing_degree_days"]

    insights = {}

    # 1️⃣ Crop Water Requirement (simple heuristic)
    cwr = (0.0023 * (temp + 17.8) * (temp - 5) * (1 + wind_speed/100))
    insights["crop_water_requirement_mm"] = round(max(cwr, 0), 2)

    # 2️⃣ Pest & Disease Risk
    if temp > 28 and humidity > 75:
        risk = "High risk"
    elif humidity > 65 and 22 < temp < 28:
        risk = "Moderate risk"
    else:
        risk = "Low risk"
    insights["pest_disease_risk"] = risk

    # 3️⃣ Optimal Planting Times
    if 20 <= soil_temp <= 30 and soil_moisture > 0.25:
        planting = "Suitable"
    else:
        planting = "Not suitable"
    insights["optimal_planting_time"] = planting

    # 4️⃣ Crop Stress Indicators
    if wsi > 0.8 or soil_moisture < 0.2:
        stress = "High stress"
    elif 0.5 < wsi <= 0.8:
        stress = "Moderate stress"
    else:
        stress = "Low stress"
    insights["crop_stress_indicator"] = stress

    return pd.Series(insights)


