def create_agriculture_dataset(api_data):
    """
    Creates structured datasets from agriculture API response

    Parameters:
    api_data (dict): The JSON API response

    Returns:
    dict: A dictionary containing multiple pandas DataFrames
    """

    datasets = {}

    # 1. Location Information Dataset
    location_data = api_data['location_information']
    datasets['location_info'] = pd.DataFrame({
        'latitude': [location_data['coordinates']['latitude']],
        'longitude': [location_data['coordinates']['longitude']],
        'elevation': [location_data['elevation_estimate']],
        'climate_zone': [location_data['climate_zone']],
        'growing_season_main': [location_data['growing_season']['main_season']],
        'growing_season_off': [location_data['growing_season']['off_season']],
        'timezone': [location_data['timezone']]
    })

    # 2. Current Weather Conditions Dataset
    current_weather = api_data['weather_analysis']['current_conditions']
    datasets['current_weather'] = pd.DataFrame({
        'temperature_2m': [current_weather['temperature_2m']],
        'relative_humidity_2m': [current_weather['relative_humidity_2m']],
        'precipitation': [current_weather['precipitation']],
        'wind_speed_10m': [current_weather['wind_speed_10m']],
        'soil_temperature_0cm': [current_weather['soil_temperature_0cm']],
        'soil_moisture_0_1cm': [current_weather['soil_moisture_0_1cm']],
        'water_stress_index': [api_data['weather_analysis']['water_stress_index']],
        'growing_degree_days': [api_data['weather_analysis']['growing_degree_days']],
        'timestamp': [api_data['metadata']['timestamp']]
    })

    # 3. Daily Forecast Dataset
    daily_forecast = api_data['weather_analysis']['daily_forecast']
    datasets['daily_forecast'] = pd.DataFrame({
        'date': daily_forecast['time'],
        'temp_max': daily_forecast['temperature_2m_max'],
        'temp_min': daily_forecast['temperature_2m_min'],
        'precipitation_sum': daily_forecast['precipitation_sum'],
        'precipitation_hours': daily_forecast['precipitation_hours'],
        'wind_speed_max': daily_forecast['wind_speed_10m_max']
    })

    # 4. Hourly Forecast Dataset
    hourly_forecast = api_data['weather_analysis']['hourly_forecast']
    datasets['hourly_forecast'] = pd.DataFrame({
        'timestamp': hourly_forecast['time'],
        'temperature_2m': hourly_forecast['temperature_2m'],
        'relative_humidity_2m': hourly_forecast['relative_humidity_2m'],
        'precipitation': hourly_forecast['precipitation'],
        'soil_temperature_0cm': hourly_forecast['soil_temperature_0cm'],
        'soil_moisture_0_1cm': hourly_forecast['soil_moisture_0_1cm']
    })

    # 5. Market Prices Dataset
    market_prices = api_data['market_analysis']['current_prices']
    market_data = []
    for crop, details in market_prices.items():
        market_data.append({
            'crop': crop,
            'price': details.get('price_per_quintal', details.get('price_per_ton', 0)),
            'price_unit': 'per_quintal' if 'price_per_quintal' in details else 'per_ton',
            'demand': details['demand'],
            'trend': details['trend']
        })
    datasets['market_prices'] = pd.DataFrame(market_data)

    # 6. Best Performing Crops Dataset
    best_crops = api_data['market_analysis']['best_performing_crops']
    best_crops_data = []
    for crop_data in best_crops:
        crop, details = crop_data
        best_crops_data.append({
            'crop': crop,
            'price': details.get('price_per_quintal', details.get('price_per_ton', 0)),
            'price_unit': 'per_quintal' if 'price_per_quintal' in details else 'per_ton',
            'demand': details['demand'],
            'trend': details['trend']
        })
    datasets['best_performing_crops'] = pd.DataFrame(best_crops_data)

    # 7. Market Trend Analysis Dataset
    trend_analysis = api_data['market_analysis']['trend_analysis']
    trend_data = []
    for crop, trend in trend_analysis.items():
        trend_data.append({
            'crop': crop,
            'market_trend': trend
        })
    datasets['market_trends'] = pd.DataFrame(trend_data)

    # 8. Agricultural Advisory Dataset
    advisory = api_data['agricultural_advisory']
    datasets['advisory'] = pd.DataFrame({
        'irrigation_advice': [advisory['irrigation_advice']],
        'pest_risk': [advisory['pest_risk_assessment']],
        'sustainability_score': [advisory['sustainability_score']],
        'timestamp': [api_data['metadata']['timestamp']]
    })

    # 9. ML Features Dataset
    ml_features = api_data['ml_training_features']['feature_vector']
    ml_data = {k: [v] for k, v in ml_features.items()}
    ml_data['data_quality_score'] = [api_data['ml_training_features']['data_quality_score']]
    ml_data['timestamp'] = [api_data['metadata']['timestamp']]
    datasets['ml_features'] = pd.DataFrame(ml_data)

    # 10. Metadata Dataset
    metadata = api_data['metadata']
    datasets['metadata'] = pd.DataFrame({
        'api_version': [metadata['api_version']],
        'area_hectares': [metadata['area_hectares']],
        'data_sources': [', '.join(metadata['data_sources'])],
        'timestamp': [metadata['timestamp']]
    })

    # 11. Soil Analysis Dataset
    soil_data = api_data['soil_analysis']
    datasets['soil_analysis'] = pd.DataFrame({
        'health_index': [soil_data['health_index']],
        'timestamp': [api_data['metadata']['timestamp']]
    })

    return datasets

# Create the datasets from the API response
agriculture_datasets = create_agriculture_dataset(api_response)

